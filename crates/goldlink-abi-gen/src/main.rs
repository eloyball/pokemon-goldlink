//! Generates `crates/goldlink-abi/src/generated.rs` from hg-engine's co-op headers.
//!
//!     cargo run -p goldlink-abi-gen            # rewrite generated.rs
//!     cargo run -p goldlink-abi-gen -- --check # fail if generated.rs is stale
//!
//! Needs libclang. The output is committed, so building the client never does
//! (dev/docs/unified-client/UC0_PROPOSAL.md §3.3).
//!
//! The headers are parsed as the ROM's compiler sees them: clang for `armv5te-none-eabi`, so
//! every `_Static_assert` in them is checked and every layout bindgen asserts is the ARM9's.
//! hg-engine's own `types.h` is never read (DECISIONS.md D1 rule 6): `TYPES_H` is predefined so
//! its include guard skips it, and `prelude/goldlink_types.h` supplies the fixed-width types.
//! Only `Coop*` types and `COOP_*` constants are generated.
//!
//! Afterwards one pass makes the output host-independent: pointers and function pointers
//! (4 bytes on the ARM9) become `u32`, and C types become Rust's fixed-width ones as the ARM9
//! sizes them (`long` is 32 bits there). The layout assertions bindgen emitted were computed by
//! clang for the ARM9, so a field that kept a host-sized type fails to compile.

use std::path::Path;
use std::process::{Command, ExitCode};

use syn::visit_mut::{self, VisitMut};
use syn::{GenericArgument, PathArguments, Type, parse_quote};

/// The headers bindgen reads, relative to the repository root. Each carries the dual
/// `CC-BY-NC-SA-4.0 OR MIT` licence (DECISIONS.md D1).
const INPUTS: [&str; 2] = [
    "hg-engine/include/coop_sync.h",
    "hg-engine/include/coop_challenge.h",
];
const PRELUDE: &str = "crates/goldlink-abi/prelude/goldlink_types.h";
const OUTPUT: &str = "crates/goldlink-abi/src/generated.rs";

fn main() -> ExitCode {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(other) => {
            eprintln!("usage: goldlink-abi-gen [--check] (unknown argument {other:?})");
            return ExitCode::from(2);
        }
    };
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let root = root.canonicalize().unwrap_or(root);
    let text = match generate(&root) {
        Ok(text) => text,
        Err(e) => {
            eprintln!("[-] {e}");
            return ExitCode::FAILURE;
        }
    };
    let out = root.join(OUTPUT);
    if check {
        let current = std::fs::read_to_string(&out).unwrap_or_default();
        if current == text {
            println!("[*] {OUTPUT} is up to date");
            ExitCode::SUCCESS
        } else {
            eprintln!("[-] {OUTPUT} is stale: run `cargo run -p goldlink-abi-gen`");
            ExitCode::FAILURE
        }
    } else {
        if let Err(e) = std::fs::write(&out, text) {
            eprintln!("[-] writing {}: {e}", out.display());
            return ExitCode::FAILURE;
        }
        println!("[*] wrote {OUTPUT}");
        ExitCode::SUCCESS
    }
}

fn generate(root: &Path) -> Result<String, String> {
    let include = root.join("hg-engine/include");
    let prelude = root.join(PRELUDE);
    let wrapper: String = INPUTS
        .iter()
        .map(|p| {
            format!(
                "#include \"{}\"\n",
                Path::new(p).file_name().unwrap().to_string_lossy()
            )
        })
        .collect();

    let bindings = bindgen::Builder::default()
        .header_contents("goldlink_abi.h", &wrapper)
        .clang_args([
            "--target=armv5te-none-eabi".to_string(),
            "-ffreestanding".to_string(),
            "-DTYPES_H".to_string(),
            "-include".to_string(),
            path_arg(&prelude),
            "-I".to_string(),
            path_arg(&include),
        ])
        // Recursively: bindgen derives Copy/Debug/Eq only for types whose field types it has
        // seen. What the recursion pulls in (the prelude's typedefs, opaque forward-declared
        // game structs behind pointers) is dropped below.
        .allowlist_type("Coop.*")
        .allowlist_var("COOP_.*")
        // Values read from RAM can be anything: plain integer constants, never Rust enums.
        .constified_enum_module("Coop.*")
        .derive_copy(true)
        .derive_debug(true)
        .derive_default(false)
        .derive_partialeq(true)
        .derive_eq(true)
        .layout_tests(true)
        .generate_comments(false)
        .use_core()
        .formatter(bindgen::Formatter::None)
        .generate()
        .map_err(|e| format!("bindgen: {e}"))?;

    let mut file: syn::File = syn::parse_str(&bindings.to_string())
        .map_err(|e| format!("parsing bindgen output: {e}"))?;
    file.items.retain(is_coop_item);
    ArmTypes.visit_file_mut(&mut file);

    let mut header = String::from(
        "// SPDX-License-Identifier: MIT OR CC-BY-NC-SA-4.0\n\
         // @generated by goldlink-abi-gen (crates/goldlink-abi-gen). Do not edit; regenerate with\n\
         // `cargo run -p goldlink-abi-gen`. Layouts are the ARM9's (armv5te-none-eabi).\n\
         // Inputs (git blob ids):\n",
    );
    for input in INPUTS.iter().chain([&PRELUDE]) {
        header.push_str(&format!("//   {input} {}\n", blob_id(root, input)?));
    }
    header.push('\n');
    Ok(header + &prettyplease::unparse(&file))
}

fn path_arg(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

/// The git blob id of a file (as `git hash-object` prints it), to name the exact inputs.
fn blob_id(root: &Path, rel: &str) -> Result<String, String> {
    let out = Command::new("git")
        .arg("hash-object")
        .arg(root.join(rel))
        .output()
        .map_err(|e| format!("git hash-object: {e}"))?;
    if !out.status.success() {
        return Err(format!("git hash-object {rel} failed"));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Makes the bindings host-independent (see the module comment).
struct ArmTypes;

impl VisitMut for ArmTypes {
    fn visit_type_mut(&mut self, ty: &mut Type) {
        if is_pointer(ty) {
            *ty = parse_quote!(u32);
            return;
        }
        if let Type::Path(p) = ty {
            if p.qself.is_none() {
                if let Some(last) = p.path.segments.last() {
                    let fixed: Option<Type> = match last.ident.to_string().as_str() {
                        // The prelude's typedefs (bindgen leaves their names in field types,
                        // renaming u8.. to u8_.. since they clash with Rust's primitives).
                        "u8_" => Some(parse_quote!(u8)),
                        "u16_" => Some(parse_quote!(u16)),
                        "u32_" => Some(parse_quote!(u32)),
                        "u64_" => Some(parse_quote!(u64)),
                        "s8" | "c_schar" => Some(parse_quote!(i8)),
                        "s16" | "c_short" => Some(parse_quote!(i16)),
                        "s32" | "BOOL" | "c_int" | "c_long" => Some(parse_quote!(i32)),
                        "s64" | "c_longlong" => Some(parse_quote!(i64)),
                        // ARM's plain char is unsigned.
                        "c_char" | "c_uchar" => Some(parse_quote!(u8)),
                        "c_ushort" => Some(parse_quote!(u16)),
                        "c_uint" | "c_ulong" => Some(parse_quote!(u32)),
                        "c_ulonglong" => Some(parse_quote!(u64)),
                        _ => None,
                    };
                    if let Some(fixed) = fixed {
                        *ty = fixed;
                        return;
                    }
                }
            }
        }
        visit_mut::visit_type_mut(self, ty);
    }
}

/// Whether a generated item is part of the co-op interface: `Coop*` types and enum modules,
/// `COOP_*` constants, and the layout assertions about them. The rest (the prelude's typedefs,
/// opaque game structs only ever reached through pointers) goes: after the pointer pass
/// nothing refers to it, and hg-engine's game types stay out of the client (DECISIONS.md D1).
fn is_coop_item(item: &syn::Item) -> bool {
    use quote::ToTokens;
    match item {
        syn::Item::Struct(s) => s.ident.to_string().starts_with("Coop"),
        syn::Item::Union(u) => u.ident.to_string().starts_with("Coop"),
        syn::Item::Enum(e) => e.ident.to_string().starts_with("Coop"),
        syn::Item::Mod(m) => m.ident.to_string().starts_with("Coop"),
        syn::Item::Type(t) => t.ident.to_string().starts_with("Coop"),
        syn::Item::Const(c) if c.ident == "_" => {
            // `const _: () = { ["Size of X"][size_of::<X>() - N]; .. }`: about which type?
            c.expr.to_token_stream().to_string().contains("Coop")
        }
        syn::Item::Const(c) => c.ident.to_string().starts_with("COOP_"),
        syn::Item::Impl(i) => i.self_ty.to_token_stream().to_string().starts_with("Coop"),
        _ => false,
    }
}

/// A data pointer, a function pointer, or bindgen's `Option<unsafe extern "C" fn(..)>`.
fn is_pointer(ty: &Type) -> bool {
    match ty {
        Type::Ptr(_) | Type::BareFn(_) => true,
        Type::Path(p) => p.path.segments.last().is_some_and(|seg| {
            seg.ident == "Option"
                && matches!(&seg.arguments, PathArguments::AngleBracketed(args)
                    if args.args.iter().any(|a| matches!(a, GenericArgument::Type(Type::BareFn(_)))))
        }),
        _ => false,
    }
}
