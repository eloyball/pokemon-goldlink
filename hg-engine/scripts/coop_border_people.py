#!/usr/bin/env python3
"""GoldLink (v0.8, UC16): the next zones' people, built into Overlay 154.

Overlay 154 (src/individual/coop_walk_out.c) makes copies of the neighbouring zones' people ahead
of a border. It read their events from the card on each tile the player stepped to, and the game
crashed at a later warp (KNOWN_RISKS #134); it reads this table instead, in the overlay's own image.

The list (data/coop/border_people.json, from the dev tool: map ids, event banks and object indices
only) names which; this copies them from the game's own zone events (a/0/3/2, as unpacked: GoldLink
builds no zone events), packed 16 bytes each, into a header the overlay includes.

    python3 scripts/coop_border_people.py <list.json> <file system root> <out.h>
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from coop_area_build import narc_parts  # noqa: E402

BG_EVENT_SIZE = 0x14
OBJECT_EVENT = struct.Struct("<HHHHHHhHHHhhHHi")  # pret ObjectEvent, 0x20 bytes
SCRIPT_NONE = 0xFFFF
MAX_BYTES = 12 * 1024  # with the overlay's code, inside its 15 KB slot (0x023C0400..0x023C4000)


def objects(member):
    """A zone events member's object events (pret: BG, object, warp, coord events)."""
    bg = struct.unpack_from("<I", member, 0)[0]
    at = 4 + bg * BG_EVENT_SIZE
    n = struct.unpack_from("<I", member, at)[0]
    at += 4
    return [OBJECT_EVENT.unpack_from(member, at + i * OBJECT_EVENT.size) for i in range(n)]


def main():
    list_path, root, out = sys.argv[1:4]
    zones = json.load(open(list_path))["zones"]
    members, _ = narc_parts(os.path.join(root, "a/0/3/2"))
    rows = []
    for zone in zones:
        objs = objects(members[zone["bank"]])
        for k in zone["objects"]:
            (oid, sprite, movement, otype, flag, script, facing, p0, p1, p2, xr, yr, x, z, y) = objs[k]
            if script == SCRIPT_NONE:
                continue  # never shown as a person (Overlay 154 skips them)
            assert oid < 256 and movement < 256 and otype < 8 and 0 <= facing < 4, (zone, k)
            assert p0 < 256 and p1 < 4 and p2 == 0 and 0 <= xr < 16 and 0 <= yr < 16, (zone, k)
            assert y % 4096 == 0 and 0 <= y >> 12 < 256, (zone, k)
            rows.append((zone["map"], x, z, sprite, flag, oid, movement,
                         otype | facing << 3 | p1 << 5, p0, xr | yr << 4, y >> 12))
    size = 16 * len(rows)
    if size > MAX_BYTES:
        sys.exit(f"border people: {size} bytes, over {MAX_BYTES}")
    lines = [
        "// GENERATED by scripts/coop_border_people.py from the game's a/0/3/2: do not edit.",
        f"#define COOP_BORDER_PEOPLE {len(rows)}",
        "static const struct CoopBorderPerson sBorderPeople[COOP_BORDER_PEOPLE] = {",
    ]
    lines += ["    { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d }," % r for r in rows]
    lines.append("};")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"border people: {len(rows)} in {len(zones)} maps, {size} bytes")


if __name__ == "__main__":
    main()
